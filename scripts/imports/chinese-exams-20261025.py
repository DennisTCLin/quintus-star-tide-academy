def add(src,loc,prompt,options,answer,explanation,kind='改編選擇',page=1,passage=None):
    n=len(rows)%len(options)
    opts=options[n:]+options[:n]
    row=dict(id=f'cx1-{src}-{loc}',sourceId=src,locator=loc,page=page,kind=kind,prompt=prompt,options=opts,answer=opts.index(options[answer]),hint='留意題目中的詞語與上下文，再比較各選項。',explanation=explanation)

async (page) => {
 const base='http://127.0.0.1:4388/output/playwright/living-archipelago/fixture.html';
 const checks={};
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base+'?offscreen');
 await page.waitForTimeout(100);
 checks.initialOffscreen=await page.locator('.archipelago-atmosphere').count()===0;
 await page.locator('.archipelago-scene').scrollIntoViewIfNeeded();
 await page.locator('.archipelago-atmosphere').waitFor();
 checks.grantHandshake=await page.locator('#motion-state').textContent()==='true';
 const first=await page.locator('.archipelago-streams').evaluate(el=>getComputedStyle(el).transform);
 await page.waitForTimeout(150);
 checks.waterMoves=first!==await page.locator('.archipelago-streams').evaluate(el=>getComputedStyle(el).transform);
 await page.getByRole('button',{name:'Ⅱ 暫停動畫'}).click();
 checks.pauseRemovesAllMotion=await page.locator('.archipelago-atmosphere').count()===0;
 await page.getByRole('button',{name:'▶ 播放動畫'}).click();
 await page.locator('.archipelago-atmosphere').waitFor();
 checks.resume=true;
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.waitForTimeout(150);
 checks.scrollOutStops=await page.locator('.archipelago-atmosphere').count()===0;
 await page.goto(base);
 await page.locator('.archipelago-atmosphere').waitFor();
 await page.getByRole('button',{name:'暫停場景測試'}).click();
 checks.suspendedStops=await page.locator('.archipelago-atmosphere').count()===0;
 await page.getByRole('button',{name:'暫停場景測試'}).click();
 await page.locator('.archipelago-atmosphere').waitFor();
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForTimeout(100);
 checks.reducedStops=await page.locator('.archipelago-atmosphere').count()===0;
 await page.getByRole('button',{name:'從群島開始英文',exact:true}).click();
 checks.staticStillNavigates=await page.locator('#chosen').textContent()==='english';
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.goto(base+'?safe=1');
 checks.safeStops=await page.locator('.archipelago-atmosphere').count()===0;
 await page.route('**/panorama-v2-*.webp',route=>route.abort());
 await page.goto(base);
 await page.waitForFunction(()=>document.querySelector('.archipelago-scene > img')?.getAttribute('src')?.includes('panorama.webp?'));
 checks.imageFallback=await page.locator('.archipelago-scene > img').evaluate(el=>el.complete&&el.naturalWidth>0);
 checks.fallbackStatic=await page.locator('.archipelago-atmosphere').count()===0;
 await page.unroute('**/panorama-v2-*.webp');
 await page.addInitScript(()=>Object.defineProperty(navigator,'connection',{value:Object.assign(new EventTarget(),{saveData:true}),configurable:true}));
 await page.goto(base);
 checks.saveDataStops=await page.locator('.archipelago-atmosphere').count()===0;
 checks.noLowResVideo=await page.locator('.archipelago-scene video').count()===0;
 return checks;
}
